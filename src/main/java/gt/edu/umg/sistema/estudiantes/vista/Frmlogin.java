    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = txtUsuario.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Campos Vacíos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Usuario usuarioAutenticado = validarCredenciales(username, password);

        if (usuarioAutenticado != null) {
            JOptionPane.showMessageDialog(this, "¡Bienvenido/a " + usuarioAutenticado.getNombre() + "!", "Acceso Concedido", JOptionPane.INFORMATION_MESSAGE);
            FrmMenuPrincipal menu = new FrmMenuPrincipal(usuarioAutenticado);
            menu.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.", "Error de Autenticación", JOptionPane.ERROR_MESSAGE);
            txtPassword.setText("");
            txtUsuario.requestFocus();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

