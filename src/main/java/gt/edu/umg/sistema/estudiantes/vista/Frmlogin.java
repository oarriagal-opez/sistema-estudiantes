    private Usuario validarCredenciales(String user, String pass) {
        String sqlUsuario = "SELECT id_usuario, username, password, rol FROM usuario WHERE LOWER(username) = LOWER(?) AND password = ?";
        Usuario usuarioAutenticado = null;

        try (Connection con = Conexion.conectar();
             PreparedStatement ps = con.prepareStatement(sqlUsuario)) {

            ps.setString(1, user);
            ps.setString(2, pass);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    int idUsuario = rs.getInt("id_usuario");
                    String username = rs.getString("username");
                    String password = rs.getString("password");
                    String rol = rs.getString("rol");

                    // Instancia el objeto Usuario con los campos disponibles
                    usuarioAutenticado = new Usuario(username, password, username, rol);
                    
                    // Carga la lista de permisos del usuario por su id_usuario
                    usuarioAutenticado.setPermisos(obtenerPermisosUsuario(idUsuario, con));
                }
            }   
        } catch (SQLException e) {
            logger.log(java.util.logging.Level.SEVERE, "Error al validar credenciales en la base de datos", e);
            JOptionPane.showMessageDialog(this, "Error al conectar con la base de datos: " + e.getMessage(), "Error de Conexión", JOptionPane.ERROR_MESSAGE);
        }

        return usuarioAutenticado;
    }

    private List<String> obtenerPermisosUsuario(int idUsuario, Connection con) throws SQLException {
        List<String> permisos = new ArrayList<>();
        // Consulta m.nombre_modulo para coincidir con las opciones guardadas desde FrmGestionUsuarios
        String sqlPermisos = "SELECT m.nombre_modulo " +
                             "FROM usuario_permiso up " +
                             "INNER JOIN modulo m ON up.id_modulo = m.id_modulo " +
                             "WHERE up.id_usuario = ?";

        try (PreparedStatement ps = con.prepareStatement(sqlPermisos)) {
            ps.setInt(1, idUsuario);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    permisos.add(rs.getString("nombre_modulo"));
                }
            }
        }
        return permisos;
    }

